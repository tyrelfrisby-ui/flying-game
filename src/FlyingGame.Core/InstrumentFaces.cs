using System;

namespace FlyingGame.Core;

/// <summary>
/// Which of a cockpit model's materials are INSTRUMENT material — a dial face with its numerals and arcs, a needle,
/// a tell-tale, a lubber line, a compass card, a printed placard legend — and so drawn with the instrument lighting
/// (FlyingGame/Instrument via Bridge InstrumentLighting): lit by the sun and sky, never below a floor, markings
/// glowing a little (Ty 2026-11-04: "make them full time legible").
///
/// The names are the glTF material names our own model builders write, fleet-wide (measured 2026-11-04 over every
/// GLB under Resources/Models): the Extra and Great Lakes (Dial_*, P3b_Dial_*, Cockpit_needle, P3b_Needle, …), the
/// Pitts' painted rear faces (RearPanel_*_Face), the 2-33 (Int_Needle, Dial_*), the J-3 (Gauge_face,
/// Panel_gauge_faces, Needle_red/black/orange). Bezels, the panel sheet, knobs and the LCD heads (CockpitDisplays
/// draws those itself) are NOT instruments here: a bezel is metal and must look like metal.
/// </summary>
public static class InstrumentFaces
{
    // BEGIN GENERATED FACE PAINT
    // Generated by tools/own_models/instrument_face_style.py.
    public const uint BlackPaint = 0x080808;
    public const uint WhitePaint = 0xFFFFFF;
    public const uint CreamPaint = 0xF5E8C3;
    public const uint InkPaint = 0x050505;
    // END GENERATED FACE PAINT
    private static readonly string[] Exact =
    {
        "Cockpit_gauge_face", "Gauge_face", "Panel_gauge_faces",
        "Cockpit_needle", "P3b_Needle", "P3b_SecondNeedle", "Int_Needle",
        "Cockpit_telltale", "P3b_Telltale", "Cockpit_lubber", "Cockpit_tc_ball",
        "Placard_text_white",
        "172_markings", "172_instrument_black", "172_normal_arc", "172_caution", "172_limit_red",
    };

    private static readonly string[] Prefixes = { "Dial_", "P3b_Dial_", "Compass_Card", "Compass_Face", "Needle_" };

    /// <summary>True for an instrument material. Accepts Unity's runtime spellings: a trailing " (Instance)" and
    /// glTFast's de-duplicating ".001"-style suffix do not change the answer.</summary>
    public static bool IsInstrument(string? materialName)
    {
        if (string.IsNullOrEmpty(materialName)) return false;
        string n = materialName!;
        const string inst = " (Instance)";
        while (n.EndsWith(inst, StringComparison.Ordinal)) n = n.Substring(0, n.Length - inst.Length);
        int dot = n.LastIndexOf('.');
        if (dot > 0 && dot < n.Length - 1 && IsDigits(n, dot + 1)) n = n.Substring(0, dot);
        if (n.IndexOf("Bezel", StringComparison.OrdinalIgnoreCase) >= 0) return false;
        foreach (string e in Exact) if (n == e) return true;
        foreach (string p in Prefixes) if (n.StartsWith(p, StringComparison.Ordinal)) return true;
        // The Pitts' and the old Extra's painted faces: RearPanel_Airspeed_Face, RearPanel_G_meter_Face, …
        return (n.StartsWith("RearPanel_", StringComparison.Ordinal) || n.StartsWith("FrontPanel_", StringComparison.Ordinal)) && n.EndsWith("_Face", StringComparison.Ordinal);
    }

    private static bool IsDigits(string s, int from)
    {
        for (int i = from; i < s.Length; i++) if (s[i] < '0' || s[i] > '9') return false;
        return true;
    }

    /// <summary>The least light an instrument face ever gets, as a fraction of full sun on it (FlyingGame/Instrument
    /// _Floor). About what a face in open shade under a clear sky reads at: a white numeral then sits near 0.3 of
    /// its full-sun brightness, which is plainly readable against a black face and not a light source.</summary>
    public const float LightFloor = 0.32f;

    /// <summary>The markings' own light, added whatever the sun is doing (_Glow), scaled by the paint's albedo, so
    /// a black face stays black. With the floor, a white marking in a cockpit in deep shadow or at night reads at
    /// about 0.55 of full sun — a post-lit panel turned well up — and in full sun it changes nothing visible
    /// (the paint is already at white).</summary>
    public const float MarkingGlow = 0.30f;
}
