using System.Diagnostics;
using System.Text.RegularExpressions;
using Xunit;
using Xunit.Abstractions;

namespace FlyingGame.FlightTests;

/// <summary>
/// StreamingAssets is generated, and these tests hold it that way.
///
/// The bug they exist for: unity/Assets/StreamingAssets/aircraft/ was gitignored AND tracked, so a new aircraft's
/// runtime config reached the player only if somebody remembered `git add -f`. The suite was happy either way —
/// it read the mirror off the working copy, which was always there — so great-lakes-like.json sat untracked for days
/// and the Great Lakes shipped with no runtime config at all (2026-10-30). Three lanes carried the same one-line
/// `git add -f` fix without any of them being the cure.
///
/// The cure is that the repo keeps exactly ONE copy of every config, in configs/ and docs/CREDITS.md. Nothing under
/// StreamingAssets is committed, so there is nothing to forget; ConfigSync writes the player's copy, and
/// BuildScript.SyncAndRequireComplete fails the build if it does not match. These tests hold the two halves of that:
/// no generated path is committed, and every generated path is ignored.
/// </summary>
public class StreamingAssetsTests
{
    private readonly ITestOutputHelper _o;
    public StreamingAssetsTests(ITestOutputHelper o) { _o = o; }

    private static string Repo
    {
        get { var d = new DirectoryInfo(AppContext.BaseDirectory); while (d != null && !Directory.Exists(Path.Combine(d.FullName, "configs", "aircraft"))) d = d.Parent; return d!.FullName; }
    }

    /// <summary>StreamingAssets paths ConfigSync generates, read out of ConfigSync's own Mirrors table so the two
    /// cannot disagree: adding a mirror there and forgetting .gitignore fails this suite.</summary>
    private static (string Source, string Dest, bool IsDirectory)[] Manifest()
    {
        string cs = File.ReadAllText(Path.Combine(Repo, "unity", "Assets", "_Project", "Scripts", "Editor", "ConfigSync.cs"));
        var table = Regex.Match(cs, @"Mirror\[\]\s+Mirrors\s*=\s*\{(.*?)\};", RegexOptions.Singleline);
        Assert.True(table.Success, "ConfigSync.cs no longer declares a `Mirror[] Mirrors = { … };` table — this test reads it");

        var rows = Regex.Matches(table.Groups[1].Value, @"new\(\s*""([^""]+)""\s*,\s*""([^""]+)""\s*(?:,\s*""([^""]+)""\s*)?\)")
            .Select(m => (Source: m.Groups[1].Value, Dest: m.Groups[2].Value, IsDirectory: m.Groups[3].Success))
            .ToArray();
        Assert.True(rows.Length >= 6, $"only {rows.Length} mirrors parsed out of ConfigSync.cs; the table's shape must have changed");
        return rows;
    }

    private static string Git(string args)
    {
        using var p = Process.Start(new ProcessStartInfo("git", args)
        {
            WorkingDirectory = Repo, RedirectStandardOutput = true, RedirectStandardError = true,
        })!;
        string stdout = p.StandardOutput.ReadToEnd();
        p.WaitForExit();
        return stdout;
    }

    /// <summary>
    /// The one file under StreamingAssets that is NOT generated, and so is allowed to be committed. commerce.json has
    /// no repo source — it is the original — and the product rules must ship exactly as reviewed.
    /// </summary>
    private static readonly string[] MayBeCommitted = { "commerce.json", "commerce.json.meta" };

    /// <summary>
    /// Nothing under StreamingAssets is committed except that one allowlisted file. This is the whole fix, and it is
    /// written as an allowlist on purpose: a manifest-driven check would only catch the mirrors ConfigSync already
    /// knows about, and every instance of this bug so far arrived as a NEW mirror somebody added and committed by hand
    /// (the aircraft configs, the four dead root challenge copies, and StreamingAssets/rigs/ on lane/claude-extra-cockpit,
    /// which is pushed and still carries its mirror). A file that is not in git cannot be the one somebody forgot to add.
    ///
    /// If this fails for a new mirror: add it to ConfigSync's Mirrors table, add it to .gitignore, and
    /// `git rm -r --cached` the committed copy. Only add to the allowlist above if the file genuinely has no repo source.
    /// </summary>
    [Fact]
    public void NothingGeneratedIsCommitted()
    {
        var tracked = Git("ls-files unity/Assets/StreamingAssets")
            .Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Select(l => l.Trim().Replace("unity/Assets/StreamingAssets/", ""))
            .ToList();
        Assert.True(tracked.Count > 0, "`git ls-files unity/Assets/StreamingAssets` returned nothing — is git reachable from the test?");

        var unexpected = tracked.Where(p => !MayBeCommitted.Contains(p)).ToList();
        Assert.True(unexpected.Count == 0,
            "StreamingAssets is generated by ConfigSync and must not be committed. These are in git:\n  "
            + string.Join("\n  ", unexpected)
            + "\n\nAdd each to ConfigSync's Mirrors table and to .gitignore, then `git rm -r --cached` it. Add it to "
            + "StreamingAssetsTests.MayBeCommitted only if it has no repo source at all.");

        _o.WriteLine($"StreamingAssets: {tracked.Count} committed file(s), all allowlisted — {string.Join(", ", tracked)}");
    }

    /// <summary>
    /// And every generated path is ignored, so one cannot drift back into the index the way the aircraft mirror did:
    /// `git add` must refuse it without -f, and `git status` must stay quiet after a sync.
    /// </summary>
    [Fact]
    public void EveryGeneratedPathIsIgnored()
    {
        var notIgnored = new List<string>();
        foreach (var m in Manifest())
        {
            string probe = m.IsDirectory ? $"unity/Assets/StreamingAssets/{m.Dest}/probe.json" : $"unity/Assets/StreamingAssets/{m.Dest}";
            if (string.IsNullOrWhiteSpace(Git($"check-ignore -- {probe}"))) notIgnored.Add(probe);

            string meta = m.IsDirectory ? $"unity/Assets/StreamingAssets/{m.Dest}.meta" : $"unity/Assets/StreamingAssets/{m.Dest}.meta";
            if (string.IsNullOrWhiteSpace(Git($"check-ignore -- {meta}"))) notIgnored.Add(meta);
        }

        Assert.True(notIgnored.Count == 0,
            "ConfigSync generates these but .gitignore does not cover them, so they can be committed and then go stale:\n  "
            + string.Join("\n  ", notIgnored));
    }

    /// <summary>
    /// Every source the manifest names exists. A mirror pointing at a path that was renamed away would make the build
    /// guard warn and carry on, which is how a config goes missing quietly.
    /// </summary>
    [Fact]
    public void EveryMirrorHasItsSource()
    {
        var missing = new List<string>();
        foreach (var m in Manifest())
        {
            string src = Path.Combine(Repo, m.Source.Replace('/', Path.DirectorySeparatorChar));
            bool there = m.IsDirectory ? Directory.Exists(src) : File.Exists(src);
            if (!there) missing.Add($"{m.Source} → StreamingAssets/{m.Dest}");
        }

        Assert.True(missing.Count == 0, "ConfigSync mirrors a repo path that is not there:\n  " + string.Join("\n  ", missing));
    }

    /// <summary>
    /// NO tracked file anywhere in the repo is matched by .gitignore. This is the general form of the bug, and the
    /// strongest statement of the fix: `git add` on such a path does nothing, only `git add -f` works, and git's
    /// behaviour is then the opposite of what a directory listing suggests. There were 63 of these on
    /// split-surfaces — 62 aircraft mirrors, plus build/cg-check.csv, a generated report committed inside the ignored
    /// build/ directory, which had gone stale at 28 rows against a 32-aircraft fleet because refreshing it would have
    /// needed the -f too.
    ///
    /// If this fails: either the file belongs in git and .gitignore should not cover it, or it is generated and should
    /// not be in git. Never reach for `git add -f` to settle it — that is the thing that hid the Great Lakes.
    /// </summary>
    [Fact]
    public void NoTrackedFileIsGitignored()
    {
        // --no-index matters: plain check-ignore says nothing about files that are already tracked, which is exactly
        // the set in question. (Without it this test passes vacuously — it did, while I was writing it.)
        string tracked = Git("ls-files");
        Assert.False(string.IsNullOrWhiteSpace(tracked), "`git ls-files` returned nothing — is git reachable from the test?");

        using var p = Process.Start(new ProcessStartInfo("git", "check-ignore --no-index --stdin -v")
        {
            WorkingDirectory = Repo, RedirectStandardInput = true, RedirectStandardOutput = true, RedirectStandardError = true,
        })!;
        p.StandardInput.Write(tracked);
        p.StandardInput.Close();
        string hits = p.StandardOutput.ReadToEnd();
        p.WaitForExit();

        var lines = hits.Split('\n', StringSplitOptions.RemoveEmptyEntries);
        Assert.True(lines.Length == 0,
            $"{lines.Length} tracked file(s) are matched by .gitignore, so `git add` skips them silently and only "
            + "`git add -f` works. Either drop the ignore rule or stop tracking the file:\n  "
            + string.Join("\n  ", lines.Take(20))
            + (lines.Length > 20 ? $"\n  … and {lines.Length - 20} more" : ""));
    }

    /// <summary>
    /// The guard is wired into all three player builds. iOS, Mac and the widget each ship the configs, and a build
    /// that skipped the call would ship whatever the working copy happened to hold.
    /// </summary>
    [Fact]
    public void EveryPlayerBuildRunsTheGuardFirst()
    {
        string cs = File.ReadAllText(Path.Combine(Repo, "unity", "Assets", "_Project", "Scripts", "Editor", "BuildScript.cs"));
        foreach (string entry in new[] { "BuildiOS", "BuildMac", "BuildWidget" })
        {
            int at = cs.IndexOf($"public static void {entry}()", StringComparison.Ordinal);
            Assert.True(at > 0, $"BuildScript.{entry} is gone; this test must be updated with it");
            int next = cs.IndexOf("BuildPipeline.BuildPlayer", at, StringComparison.Ordinal);
            Assert.True(next > at, $"BuildScript.{entry} no longer calls BuildPlayer");
            Assert.Contains("ConfigSync.SyncAndRequireComplete()", cs[at..next]);
        }
    }
}
