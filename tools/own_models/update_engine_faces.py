"""Embed regenerated Great Lakes engine faces without rebuilding geometry.

Run after make_gl_dials.py. Only dedicated named materials are changed. Pitts live
engine faces come from CockpitDials and are generated by make_live_dials.py.
"""
import copy
import json
import struct
from pathlib import Path

from glb_visuals import Glb

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / 'unity/Assets/_Project/Resources/Models/great-lakes-like/great-lakes-like-own.glb'
KEYS = ('TACH', 'MP', 'OIL', 'OILPRESS', 'CHT', 'HOBBS', 'MAG')


def main():
    g = Glb(PATH)
    original = copy.deepcopy(g.doc)
    original_bin = bytes(g.bin)
    for key in KEYS:
        material = next(m for m in g.doc['materials'] if m.get('name') == 'Dial_' + key)
        binding = material['pbrMetallicRoughness']['baseColorTexture']
        texture = copy.deepcopy(g.doc['textures'][binding['index']])
        image = dict(bufferView=g.data((ROOT / 'tools/own_models/art' / ('gl-dial-' + key.lower() + '.png')).read_bytes()), mimeType='image/png')
        g.doc['images'].append(image)
        texture['source'] = len(g.doc['images']) - 1
        g.doc['textures'].append(texture)
        material['pbrMetallicRoughness']['baseColorTexture'] = dict(binding, index=len(g.doc['textures']) - 1)
    # Do not call Glb.save: its general styling pass is outside this texture-only operation.
    for field in ('nodes', 'meshes', 'accessors', 'scenes'):
        assert original[field] == g.doc[field], field
    assert bytes(g.bin[:len(original_bin)]) == original_bin
    g.doc['buffers'][0]['byteLength'] = len(g.bin)
    js = json.dumps(g.doc, separators=(',', ':')).encode()
    js += b' ' * (-len(js) % 4)
    binary = bytes(g.bin) + b'\0' * (-len(g.bin) % 4)
    PATH.write_bytes(struct.pack('<4sII', b'glTF', 2, 28 + len(js) + len(binary)) +
                     struct.pack('<I4s', len(js), b'JSON') + js +
                     struct.pack('<I4s', len(binary), b'BIN\0') + binary)
    print('7 Great Lakes engine/control faces embedded; all existing geometry and buffer bytes preserved.')


if __name__ == '__main__':
    main()
