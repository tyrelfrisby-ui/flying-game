using System.Text;
namespace IslandTerrainGen;

/// <summary>
/// Writes src/FlyingGame.Core/IslandRelief.Generated.cs: every lattice as a compact, lossless-after-
/// quantization stream inside base64 string literals. Heights are stored at 5 cm (h = q * 0.05 - 30), coded
/// as the residual of a planar predictor (left + up - upleft), zig-zag varints; the byte channels are run-
/// length coded. The format is decoded by IslandRelief.Decode and by tools/island/relief.py (parity checks).
/// </summary>
public static class Export
{
    public const double Quantum = .05, Offset = 30;
    public static ushort Q(double h) => (ushort)Math.Clamp(Math.Round((h + Offset) / Quantum), 0, 65535);
    public static double Dq(ushort q) => q * Quantum - Offset;

    public static byte[] Encode(IReadOnlyList<Mass> masses)
    {
        var o = new List<byte>();
        void V(ulong v) { while (v >= 0x80) { o.Add((byte)(v | 0x80)); v >>= 7; } o.Add((byte)v); }
        void D(double d) => o.AddRange(BitConverter.GetBytes(d));
        o.AddRange(Encoding.ASCII.GetBytes("IRL2")); V((ulong)masses.Count);
        foreach (var m in masses)
        {
            var g = m.G; D(g.E0); D(g.N0); D(g.Cell); V((ulong)g.W); V((ulong)g.H);
            var q = new int[g.N]; for (int k = 0; k < g.N; k++) q[k] = Q(m.H[k]);
            for (int j = 0; j < g.H; j++) for (int i = 0; i < g.W; i++)
            {
                int k = j * g.W + i; int pred = i > 0 && j > 0 ? q[k - 1] + q[k - g.W] - q[k - g.W - 1] : i > 0 ? q[k - 1] : j > 0 ? q[k - g.W] : 0;
                long r = q[k] - pred; V((ulong)((r << 1) ^ (r >> 63)));
            }
            foreach (var ch in Channels(m))
            {
                int k = 0;
                while (k < g.N) { byte v = ch[k]; int run = 1; while (k + run < g.N && ch[k + run] == v) run++; o.Add(v); V((ulong)run); k += run; }
            }
        }
        return o.ToArray();
    }
    /// <summary>The eight byte channels, in format order (IRL2): ice fraction, debris cover, wetness (log
    /// discharge), local equilibrium-line altitude (IslandRelief.ElaBaseM + ElaStepM per step), then the
    /// surface classes of Surfaces.Apply: glacier/patch SNOW, ICE undulation weight, CREVASSE intensity, LEDGE.</summary>
    public static byte[][] Channels(Mass m)
    {
        var g = m.G; var a = new byte[8][]; for (int c = 0; c < 8; c++) a[c] = new byte[g.N];
        for (int k = 0; k < g.N; k++)
        {
            a[0][k] = B(m.Ice[k]); a[1][k] = B(m.Debris[k]); a[2][k] = B(m.Wet[k]);
            a[3][k] = (byte)Math.Clamp(Math.Round((Climate.Ela(m.Rain[k]) - FlyingGame.Core.IslandRelief.ElaBaseM) / FlyingGame.Core.IslandRelief.ElaStepM), 0, 255);
            a[4][k] = B(m.Snow[k]); a[5][k] = B(m.Rough[k]); a[6][k] = B(m.Crevasse[k]); a[7][k] = B(m.Ledge[k]);
        }
        return a;
    }
    static byte B(double v) => (byte)Math.Clamp(Math.Round(v * 255), 0, 255);

    public static string Source(byte[] data, string summary)
    {
        string b64 = Convert.ToBase64String(data);
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> tools/island/TerrainGen (dotnet run -c Release -- generate); do not edit.\n");
        sb.Append("// " + summary.Replace("\n", "\n// ") + "\n");
        sb.Append("// </auto-generated>\nnamespace FlyingGame.Core;\n\ninternal static class IslandReliefData\n{\n");
        sb.Append($"    public const int Bytes = {data.Length};\n");
        sb.Append($"    public const string Sha256 = \"{Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(data)).ToLowerInvariant()}\";\n");
        sb.Append("    public static readonly string[] Base64 =\n    {\n");
        const int chunk = 16000;
        for (int i = 0; i < b64.Length; i += chunk) sb.Append("        \"").Append(b64, i, Math.Min(chunk, b64.Length - i)).Append("\",\n");
        sb.Append("    };\n}\n");
        return sb.ToString();
    }
}
