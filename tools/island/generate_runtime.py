#!/usr/bin/env python3
"""Compile approved world tables to C#; no runtime file reads or StreamingAssets mirrors.
Run after docs/pending/tools/generate_island.py. --check never writes.
"""
import argparse,hashlib,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'docs/pending/tools'))
import generate_island as g

def compile_data():
 w=g.W
 # Only world-owned geometry. Supplied IFR stays in docs; derived terrain reservations
 # are geometry budgets, not operational stations/procedures.
 data=dict(w,fields=g.FIELDS,land_polygons=g.LAND,clearance_budgets=g.CLEARANCE_ENVELOPES,zone_geometry=json.loads((g.ROOT/'island-fit-check.json').read_text())['zone_geometry'])
 methods=[]
 def emit(v):
  if isinstance(v,dict):
   args=[('('+json.dumps(k)+', '+emit(x)+')') for k,x in v.items()];expr='IslandValue.Map('+', '.join(args)+')'
  elif isinstance(v,(list,tuple)):expr='IslandValue.Array('+', '.join(emit(x) for x in v)+')'
  elif v is None:return 'IslandValue.Empty'
  elif isinstance(v,bool):return 'IslandValue.Scalar('+str(v).lower()+')'
  elif isinstance(v,(int,float)):return 'IslandValue.Scalar('+repr(float(v))+')'
  else:return 'IslandValue.Scalar('+json.dumps(v,ensure_ascii=True)+')'
  name='N'+str(len(methods));methods.append('');methods[int(name[1:])]='    private static IslandValue '+name+'() => '+expr+';';return name+'()'
 root=emit(data)
 return '// Generated by tools/island/generate_runtime.py. DO NOT EDIT.\nnamespace FlyingGame.Core;\npublic static class IslandData\n{\n    public const string SpecSha256 = "'+hashlib.sha256((g.ROOT/'island-spec.json').read_bytes()).hexdigest()+'";\n    public static readonly IslandValue World = '+root+';\n'+'\n'.join(methods)+'\n}\n'

p=ROOT/'src/FlyingGame.Core/IslandData.Generated.cs';text=compile_data();check='--check'in sys.argv
if check:
 assert p.read_text()==text,'Stale compiled world tables'
 print('Compiled world tables match approved spec and exact active zone polygons.')
else:p.write_text(text);print('Generated',p,len(text),'bytes')
